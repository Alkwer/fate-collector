import { expect, test } from '@playwright/test'
import { action, capture, setup, state, write } from './overlay-support'

test('automatic offers import without F9 and closing the panel revokes stale actions', async ({ page }) => {
  await setup(page)
  const first = await capture(page, true)
  await action(page, 'use-offer')
  await expect.poll(async () => (await state(page))?.actions.some(item => item.id.startsWith('collect:'))).toBe(true)
  const collect = (await state(page))!.actions.find(item => item.id.startsWith('collect:'))!.id
  await action(page, 'last-offer')
  await expect(page.getByRole('checkbox', { name: 'Last offer in this area' })).toBeChecked()
  await expect.poll(async () => (await state(page))?.detail).toContain('Last offer.')
  await action(page, 'more-offers')
  await expect(page.getByRole('checkbox', { name: 'Last offer in this area' })).not.toBeChecked()
  await expect.poll(async () => (await state(page))?.actions.some(item => item.id === 'last-offer')).toBe(true)
  await action(page, collect)
  await expect(page.locator('.collected-fates li')).toHaveCount(1)
  await write(page, 'capture.json', { protocol: 1, captureId: null, phase: 'watching', updatedAt: Date.now() })
  await expect.poll(async () => (await state(page))?.title).toBe('Watching for Fate cards')
  expect((await state(page))!.actions).toEqual([])
  expect((await state(page))!.rows).toEqual([])
  await write(page, 'capture.json', { protocol: 1, captureId: null, phase: 'paused', updatedAt: Date.now() })
  await expect.poll(async () => (await state(page))?.title).toBe('Automatic detection paused')
  const second = await capture(page, true)
  expect(second).not.toBe(first)
  await action(page, 'use-offer')
  await expect.poll(async () => (await state(page))?.rows.length).toBe(1)
  await expect(page.locator('.collected-fates li')).toHaveCount(1)
})

test('overlay confirms an area, records a choice once, undoes and clears an area explicitly', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await setup(page)
  await capture(page)
  await action(page, 'use-offer')
  await expect.poll(async () => (await state(page))?.status).toBe('check')
  const collect = (await state(page))!.actions.find(item => item.id.startsWith('collect:'))!.id
  await action(page, collect, { revision: crypto.randomUUID() })
  await expect.poll(async () => (await state(page))?.notice).toContain('expired')
  await expect(page.locator('.collected-fates li')).toHaveCount(0)
  await action(page, collect)
  await expect(page.locator('.collected-fates li')).toHaveCount(1)
  await expect.poll(async () => (await state(page))?.status).toBe('collected')
  await page.waitForTimeout(1500)
  await expect(page.locator('.collected-fates li')).toHaveCount(1)
  await action(page, 'undo')
  await expect(page.locator('.collected-fates li')).toHaveCount(0)
  await expect.poll(async () => (await state(page))?.actions.some(item => item.id === collect)).toBe(true)
  await action(page, collect)
  await expect.poll(async () => (await state(page))?.status).toBe('collected')
  await action(page, 'new-area')
  await expect.poll(async () => (await state(page))?.title).toBe('Start a new area?')
  await expect(page.locator('.collected-fates li')).toHaveCount(1)
  await action(page, 'confirm-new-area')
  await expect.poll(async () => (await state(page))?.title).toBe('New area started')
  await expect(page.locator('.collected-fates li')).toHaveCount(0)
  await action(page, 'undo')
  await expect(page.locator('.collected-fates li')).toHaveCount(1)
  await expect.poll(async () => (await state(page))?.status).toBe('confirm-area')
  await action(page, 'continue-area')
  await expect.poll(async () => (await state(page))?.status).toBe('collected')
  expect(errors).toEqual([])
})

test('overlay stops old advice on F9 and keeps a single writer across tabs', async ({ page, context }) => {
  await setup(page)
  const captureId = await capture(page)
  await action(page, 'use-offer')
  await expect.poll(async () => (await state(page))?.rows.length).toBe(1)
  const other = await context.newPage()
  await other.addInitScript(() => {
    Object.defineProperty(window, 'showDirectoryPicker', { configurable: true, value: async () => (await navigator.storage.getDirectory()).getDirectoryHandle('captures') })
  })
  await other.goto('/')
  await other.getByRole('button', { name: 'More actions', exact: true }).click()
  await other.getByRole('button', { name: 'In-game overlay', exact: true }).click()
  await other.getByRole('button', { name: 'Connect overlay folder' }).click()
  await expect(other.getByRole('dialog').getByRole('alert')).toContainText('another tab')
  await other.close()
  await write(page, 'capture.json', { protocol: 1, captureId, phase: 'capturing', updatedAt: Date.now() })
  await expect.poll(async () => (await state(page))?.rows).toEqual([])
  await expect.poll(async () => (await state(page))?.actions).toEqual([])
  await page.getByRole('button', { name: 'More actions', exact: true }).click()
  await page.getByRole('button', { name: 'In-game overlay', exact: true }).click()
  await page.getByRole('button', { name: 'Disconnect overlay' }).click()
  await expect.poll(async () => (await state(page))?.writtenAt).toBe(0)
})

test('overlay setup fits desktop, tablet and mobile and supports keyboard dismissal', async ({ page }, testInfo) => {
  await setup(page)
  await page.getByRole('button', { name: 'More actions', exact: true }).click()
  await page.getByRole('button', { name: 'In-game overlay', exact: true }).click()
  for (const [label, width, height] of [['desktop', 1440, 1000], ['tablet', 820, 1000], ['mobile', 390, 844]] as const) {
    await page.setViewportSize({ width, height })
    const panel = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: 'In-game overlay', exact: true }) })
    await expect(panel).toBeVisible()
    expect(await panel.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`overlay-${label}.png`), fullPage: true })
    await panel.locator('.detail-body').evaluate(element => { element.scrollTop = element.scrollHeight })
    await page.screenshot({ path: testInfo.outputPath(`overlay-${label}-bottom.png`), fullPage: true })
    await panel.locator('.detail-body').evaluate(element => { element.scrollTop = 0 })
  }
  await page.keyboard.press('Escape')
  await expect(page.getByRole('heading', { name: 'In-game overlay', exact: true })).not.toBeVisible()
})

