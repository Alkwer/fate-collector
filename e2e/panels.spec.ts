import { test, expect } from '@playwright/test'
import { closePanels, openPanel } from './ui'

for (const theme of ['mineral', 'trail']) test(`${theme}: secondary tasks use focused panels without accordion rows`, async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await expect(page.locator('details, summary')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Connect captures folder', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Edit details', exact: true })).toHaveCount(0)
  await openPanel(page, '.more-actions')
  await page.getByLabel('Appearance').selectOption(theme)
  await expect(page.locator('html')).toHaveAttribute('data-theme', theme)
  await page.keyboard.press('Tab')
  expect(await page.evaluate(() => document.activeElement?.closest('dialog')?.open)).toBe(true)
  await closePanels(page)
  await expect(page.getByRole('button', { name: 'More actions', exact: true })).toBeFocused()
  await openPanel(page, '.advanced-panel')
  await page.getByRole('textbox', { name: 'Notes', exact: true }).fill('Keep this draft when the panel closes')
  await closePanels(page)
  await openPanel(page, '.advanced-panel')
  await expect(page.getByRole('textbox', { name: 'Notes', exact: true })).toHaveValue('Keep this draft when the panel closes')
  await closePanels(page)
  await openPanel(page, '.map-capture-connection')
  await expect(page.getByRole('dialog', { name: 'Local review', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await closePanels(page)
  await page.getByRole('button', { name: /Saved offers/ }).click()
  await expect(page.locator('details, summary')).toHaveCount(0)
})
