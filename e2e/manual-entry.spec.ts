import { test, expect } from '@playwright/test'
import { closePanels, openPanel } from './ui'

test('enters a manual offer, saves it and starts the next without changing the collection', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Add Fate manually', exact: true }).click()
  const entry = page.getByRole('dialog', { name: 'Add Fate manually', exact: true })
  await entry.getByRole('searchbox', { name: 'Find a Fate' }).fill('alch')
  await entry.getByRole('button', { name: 'Choose Alchemist', exact: true }).click()
  await expect(entry.getByLabel('Tier', { exact: true })).toHaveValue('')
  await entry.getByRole('button', { name: 'Tier 2', exact: true }).click()
  await entry.getByRole('button', { name: 'Add Additional Currency Items Kind unknown', exact: true }).click()
  await entry.getByRole('button', { name: 'Set reward kind', exact: true }).click()
  const details = page.getByRole('dialog', { name: 'Reward 1 details', exact: true })
  await expect(details.getByRole('combobox', { name: 'Kind', exact: true })).toHaveValue('unknown')
  await details.getByRole('combobox', { name: 'Kind', exact: true }).selectOption('regular')
  await details.getByRole('button', { name: 'Done', exact: true }).click()
  await entry.getByRole('button', { name: 'Increase reward 1 count' }).click({ clickCount: 2 })
  await entry.getByRole('button', { name: 'Add & enter another' }).click()
  await expect(entry.getByRole('status')).toHaveText('Alchemist added to the offer.')
  await expect(entry.getByRole('searchbox', { name: 'Find a Fate' })).toBeFocused()
  await entry.getByRole('button', { name: 'Choose Sanguine', exact: true }).click()
  await entry.getByRole('button', { name: 'Add to offer', exact: true }).click()
  await expect(entry).not.toBeVisible()
  await expect(page.locator('#advisor-heading')).toBeFocused()
  await expect(page.locator('.fate-list > li')).toHaveCount(2)
  await page.getByRole('button', { name: 'Save offer', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Saved', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Add Alchemist to collected', exact: true }).click()
  await expect(page.locator('.collected-fates > li')).toHaveCount(1)

  await page.getByRole('button', { name: 'Add Fate manually', exact: true }).click()
  await expect(entry).toContainText('Start the next offer.')
  await entry.getByRole('button', { name: 'Choose Butcher', exact: true }).click()
  await entry.getByRole('button', { name: 'Add & enter another' }).click()
  await entry.getByRole('button', { name: 'Choose Dryad', exact: true }).click()
  await entry.getByRole('button', { name: 'Add to offer', exact: true }).click()
  await expect(page.locator('.fate-list > li')).toHaveCount(2)
  await expect(page.locator('.fate-list')).toContainText('Butcher')
  await expect(page.locator('.fate-list > li > .fate-title h3')).toHaveText(['Butcher', 'Dryad'])
  await expect(page.locator('.collected-fates')).toContainText('Alchemist')
  const workspace = await page.evaluate(() => JSON.parse(sessionStorage.getItem('fate-collector.advisor-area.v2')!))
  expect(workspace.offerIds).toHaveLength(2)
  expect(workspace.collection.cards[0]).toMatchObject({ name: 'Alchemist', tier: 2, rewards: [{ label: 'Additional Currency Items', kind: 'regular', count: 3, identified: true }] })
  await page.getByRole('button', { name: /Saved offers/ }).click()
  await page.getByRole('combobox', { name: 'Show', exact: true }).selectOption('live')
  await expect(page.locator('.history-table tbody')).toContainText('Alchemist')
})

test('keeps unknown data and a custom name, preserves unfinished input and limits counts', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const add = page.getByRole('button', { name: 'Add Fate manually', exact: true })
  await add.click()
  const entry = page.getByRole('dialog', { name: 'Add Fate manually', exact: true })
  await entry.getByRole('searchbox', { name: 'Find a Fate' }).fill('A new Fate with a long name')
  await entry.getByRole('button', { name: 'Use a different name: A new Fate with a long name' }).click()
  await entry.getByRole('button', { name: 'Unknown reward', exact: true }).click()
  await expect(entry.getByRole('button', { name: 'Decrease reward 1 count' })).toBeDisabled()
  await entry.getByLabel('Tier', { exact: true }).fill('101')
  await expect(entry.getByRole('button', { name: 'Add to offer', exact: true })).toBeDisabled()
  await entry.getByLabel('Tier', { exact: true }).fill('')
  await entry.getByRole('button', { name: 'Increase reward 1 count' }).click()
  await page.keyboard.press('Escape')
  await expect(add).toBeFocused()
  await add.click()
  await expect(entry.getByLabel('Fate name', { exact: true })).toHaveValue('A new Fate with a long name')
  await entry.getByRole('button', { name: 'Add to offer', exact: true }).click()
  await page.getByRole('button', { name: 'Add A new Fate with a long name to collected', exact: true }).click()
  const workspace = await page.evaluate(() => JSON.parse(sessionStorage.getItem('fate-collector.advisor-area.v2')!))
  expect(workspace.collection.cards[0]).toMatchObject({ tier: null, rewards: [{ label: '', kind: 'unknown', threshold: null, count: 2, identified: false }] })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('adds catalog rewards without fields and opens details only for a custom reward', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Add Fate manually', exact: true }).click()
  const entry = page.getByRole('dialog', { name: 'Add Fate manually', exact: true })
  await entry.getByRole('button', { name: 'Choose Alchemist', exact: true }).click()
  await entry.getByRole('button', { name: 'Add Exceptional Gem Combo · needs 3', exact: true }).click({ clickCount: 2 })
  await expect(entry.getByRole('list', { name: 'Selected rewards' }).locator(':scope > li')).toHaveCount(1)
  await expect(entry.getByRole('group', { name: 'Reward 1 count', exact: true })).toContainText('2×')
  await expect(entry.getByRole('region', { name: 'Fate rewards' }).getByRole('textbox')).toHaveCount(0)
  await entry.getByRole('button', { name: 'Other reward', exact: true }).click()
  const details = page.getByRole('dialog', { name: 'Reward 2 details', exact: true })
  await expect(details).toBeVisible()
  await details.getByLabel('Reward name', { exact: true }).fill('Armour')
  await details.getByRole('combobox', { name: 'Kind', exact: true }).selectOption('regular')
  await page.keyboard.press('Escape')
  await expect(entry).toBeVisible()
  await entry.getByRole('button', { name: 'Add to offer', exact: true }).click()
  await page.getByRole('button', { name: 'Add Alchemist to collected', exact: true }).click()
  const workspace = await page.evaluate(() => JSON.parse(sessionStorage.getItem('fate-collector.advisor-area.v2')!))
  expect(workspace.collection.cards[0].rewards).toMatchObject([
    { label: 'Exceptional Gem', kind: 'combo', threshold: 3, count: 2, identified: true },
    { label: 'Armour', kind: 'regular', threshold: null, count: 1, identified: true },
  ])
})

test('does not replace a used unsaved offer when the replacement is cancelled', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Add Fate manually', exact: true }).click()
  const entry = page.getByRole('dialog', { name: 'Add Fate manually', exact: true })
  await entry.getByRole('button', { name: 'Choose Alchemist', exact: true }).click()
  await entry.getByRole('button', { name: 'Add to offer', exact: true }).click()
  await page.getByRole('button', { name: 'Add Alchemist to collected', exact: true }).click()
  await page.getByRole('button', { name: 'Add Fate manually', exact: true }).click()
  await entry.getByRole('button', { name: 'Choose Butcher', exact: true }).click()
  page.once('dialog', dialog => dialog.dismiss())
  await entry.getByRole('button', { name: 'Add to offer', exact: true }).click()
  await expect(entry.getByLabel('Fate name', { exact: true })).toHaveValue('Butcher')
  await closePanels(page)
  await expect(page.locator('.fate-list')).toContainText('Alchemist')
  await expect(page.locator('.fate-list')).not.toContainText('Butcher')
  await openPanel(page, '.advanced-panel')
  await expect(page.getByRole('dialog', { name: 'Edit details', exact: true }).getByLabel('Fate name', { exact: true })).toHaveValue('Alchemist')
})
